// أدوات مشتركة لاختبارات القسم اللفظي (المحاضرة ٢ فما بعد)
(() => {
  const REL = {
    syn: { name: "ترادف (كلمتان بمعنى واحد)", pairs: [["ولوج", "دخول"], ["أسد", "ليث"], ["يلبّي", "يجيب"], ["حطام", "هشيم"], ["ذائع", "شائع"], ["بذل", "عطاء"], ["سرور", "فرح"], ["هدوء", "سكينة"], ["جود", "كرم"], ["عزم", "إصرار"], ["حزن", "أسى"], ["بأس", "شدة"]] },
    opp: { name: "تضاد (كلمتان متعاكستان)", pairs: [["غضب", "حلم"], ["جوع", "شبع"], ["حاد", "مثلم"], ["كريم", "بخيل"], ["عسر", "يسر"], ["قسوة", "لين"], ["شجاعة", "جبن"], ["صدق", "كذب"], ["غنى", "فقر"], ["إقبال", "إدبار"], ["واسع", "ضيق"], ["أمانة", "خيانة"]] },
    gen: { name: "عام : خاص (الثاني نوع من الأول)", pairs: [["وعاء", "قِدر"], ["طائر", "نسر"], ["شجرة", "نخلة"], ["سلاح", "سيف"], ["فاكهة", "تفاح"], ["معدن", "حديد"], ["مركبة", "شاحنة"], ["حيوان", "غزال"], ["زهرة", "ياسمين"]] },
    sib: { name: "كلاهما من فصيلة أو نوع واحد", pairs: [["نمر", "ذئب"], ["فيل", "ثور"], ["صحن", "دلو"], ["قمح", "شعير"], ["ورد", "فل"], ["نحاس", "حديد"], ["عصفور", "حمام"], ["تفاح", "برتقال"]] },
    afflict: { name: "الشيء : ما يصيبه من ضعف أو تلف", pairs: [["عظم", "وهن"], ["حديد", "صدأ"], ["أسنان", "تسوّس"], ["نبات", "ذبول"], ["ثوب", "بلى"], ["خشب", "تآكل"]] },
    produce: { name: "المُنتِج : ما يُنتجه", pairs: [["نحلة", "عسل"], ["بقرة", "حليب"], ["دودة القز", "حرير"], ["شجرة", "ثمر"], ["سحاب", "مطر"], ["شمس", "ضوء"]] },
    cause: { name: "سبب : نتيجة", pairs: [["إهمال", "فشل"], ["اجتهاد", "نجاح"], ["عمل", "قوة"], ["كسل", "تخمة"], ["برد", "زكام"], ["مطر", "سيل"], ["سهر", "إرهاق"]] },
    end: { name: "الشيء : مرحلته الأخيرة", pairs: [["عمر", "شيخوخة"], ["نهار", "غروب"], ["رواية", "خاتمة"], ["سنة", "ذو الحجة"], ["سباق", "خط النهاية"], ["قصيدة", "قافية الختام"]] },
    material: { name: "الشيء : المادة المصنوع منها", pairs: [["باب", "خشب"], ["نافذة", "زجاج"], ["سيف", "حديد"], ["ثوب", "قطن"], ["خاتم", "ذهب"], ["إناء", "فخار"], ["كوب", "زجاج"]] },
    tool: { name: "أداة : وظيفتها", pairs: [["قلم", "كتابة"], ["مقص", "قص"], ["ميزان", "وزن"], ["مجهر", "تكبير"], ["منشار", "نشر"], ["مسطرة", "قياس"], ["إبرة", "خياطة"]] },
    part: { name: "جزء : كل", pairs: [["صفحة", "كتاب"], ["غصن", "شجرة"], ["حرف", "كلمة"], ["لاعب", "فريق"], ["دقيقة", "ساعة"], ["آية", "سورة"]] }
  };
  const SYM = new Set(["syn", "opp", "sib"]); // علاقات لا يغيرها عكس الترتيب
  const fmt = p => `${p[0]} : ${p[1]}`;
  function analogy(keys, from, to, extra) {
    return { title: "التناظر اللفظي", from, to, extra, gen(R, h) {
      const k = R.pick(keys), rel = REL[k];
      const [stem, ans] = R.shuffle(rel.pairs).slice(0, 2);
      const otherKeys = R.shuffle(Object.keys(REL).filter(x => x !== k)).slice(0, 3);
      let wrong = otherKeys.map(x => R.pick(REL[x].pairs));
      if (!SYM.has(k) && R.next() < .6) { const p = R.pick(rel.pairs.filter(q => q !== stem && q !== ans)); if (p) wrong[0] = [p[1], p[0]]; }
      const o = h.strOptions(R, fmt(ans), wrong.map(fmt));
      return { style: k, sig: `${k}:${fmt(stem)}:${fmt(ans)}`, body: `اختر الإجابة التي تماثل العلاقة في الكلمتين: ${fmt(stem)}`, ...o,
        steps: [`نكوّن جملة مفيدة تربط الكلمتين: «${stem[0]}» و«${stem[1]}»، والعلاقة: ${rel.name}.`, `نطبق الجملة نفسها على الخيارات وبالترتيب نفسه: «${fmt(ans)}» تحقق العلاقة ✓.`,
          ...wrong.map(p => `«${fmt(p)}»: ${rel.pairs.some(x => x[0] === p[1] && x[1] === p[0]) ? "العلاقة نفسها لكن الترتيب معكوس ✗" : "علاقة مختلفة ✗"}`)], explanation: fmt(ans) };
    } };
  }
  function completion(bank, from, to) {
    return { title: "إكمال الجمل", from, to, gen(R, h) {
      const i = R.int(0, bank.length - 1), [s, opts, why] = bank[i];
      return { style: "c" + (i % 4), sig: `c:${i}`, body: `اختر الإجابة المناسبة لإكمال الفراغات:\n${s}`, ...h.strOptions(R, opts[0], opts.slice(1)),
        steps: ["نقرأ الجملة كاملة، ونبحث عن الكلمات المفتاحية وأدوات الربط التي تحدد اتجاه المعنى.", why, `نعوّض «${opts[0]}» في الفراغات فيستقيم المعنى ✓.`], explanation: opts[0] };
    } };
  }
  const STOP = /^(من|إذا|إن|أن|على|في|كما|لا|ما|عند|إلا|ثم|قد|التي|الذي|بين|عن|إلى|كل|هو|هي)$/;
  function error(bank, from, to) {
    return { title: "الخطأ السياقي", from, to, gen(R, h) {
      const i = R.int(0, bank.length - 1), [s, right, wrongW] = bank[i], shown = s.replace(right, wrongW);
      const words = [...new Set(shown.replace(/[،؛.:«»]/g, "").split(/\s+/).filter(w => w.length > 2 && w !== wrongW && !STOP.test(w)))];
      return { style: "e", sig: `e:${i}`, body: `حدد الكلمة التي لا يتفق معناها مع المعنى العام للجملة:\n«${shown}»`, ...h.strOptions(R, wrongW, R.shuffle(words).slice(0, 3)),
        steps: ["نحدد المعنى العام للجملة أولًا، ثم نبحث عن الكلمة التي تناقضه.", `كلمة «${wrongW}» تُفسد المعنى، والصواب «${right}».`, `الجملة الصحيحة: «${s}».`], explanation: wrongW };
    } };
  }
  function passage(P, from, to) {
    return { title: `استيعاب المقروء: ${P.title}`, from, to, gen(R, h) {
      const qi = R.int(0, P.qs.length - 1), [q, opts, why] = P.qs[qi];
      return { style: "q" + qi, sig: `${P.title}:${qi}`, body: `اقرأ النص ثم أجب:\n\n${P.text}\n\n${q}`, ...h.strOptions(R, opts[0], opts.slice(1)),
        steps: [`المطلوب: ${q.replace(/[:؟]$/, "")}.`, `نعود إلى النص ونبحث عن الجملة المرتبطة بالسؤال: ${why}`, `إذن الإجابة: «${opts[0]}».`, "تذكّر: نستبعد الخيارات التي فيها تعميم أو معلومة لم يذكرها النص."], explanation: opts[0] };
    } };
  }
  window.VERBAL = { REL, analogy, completion, error, passage };
})();
