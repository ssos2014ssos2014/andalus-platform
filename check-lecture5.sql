select id, section, title,
       parts -> 0 ->> 'url'      as "رابط الملف المرفوع",
       parts -> 0 ->> 'file_name' as "اسم الملف",
       parts -> 0 ->> 'drive_id' as "Drive"
from lectures where id in (5, 1005) order by id;

